import { useEffect, useState } from 'react'
import { Sparkles, Download, Loader2, ShieldCheck } from 'lucide-react'
import Pane from '../Pane.jsx'
import { useOperation } from '../../context/OperationContext.jsx'
import { aarReport, mission, evidenceSources } from '../../data/mockData.js'
import { bus } from '../../lib/bus.js'

function buildReportMarkdown(evidence, confidence) {
  return [
    `# AFTER-ACTION REPORT — ${mission.title}`,
    `\n> PREVIEW // MOCK — fictional scenario, generated by Ghost Command: ReconOps demo\n`,
    `## Question\n${mission.question}\n`,
    `## Answer\nStaging confirmed — ${Math.round(confidence * 100)}% confidence from ${evidence.length} independent sources.\n`,
    `## Evidence\n${evidenceSources.filter((s) => evidence.includes(s.id)).map((s) => `- **${s.label}:** ${s.finding}`).join('\n')}\n`,
    `## Statistics\n${aarReport.stats.map((s) => `- ${s.label}: ${s.value}`).join('\n')}\n`,
    `## Timeline\n${aarReport.timeline.map((t) => `- **${t.t}** [${t.sev}] ${t.label}`).join('\n')}\n`,
    `## Findings\n${aarReport.findings}\n`,
    `## Lessons Learned\n${aarReport.lessons}\n`,
    `## Recommendation\n${aarReport.recommendation}\n`,
  ].join('\n')
}

export default function DebriefView() {
  const { evidence, confidence, reportFiled, setReportFiled } = useOperation()
  const [thinking, setThinking] = useState(false)

  const generate = () => {
    setThinking(true)
    setTimeout(() => { setThinking(false); setReportFiled(true) }, 1400)
  }
  // eslint-disable-next-line react-hooks/exhaustive-deps
  useEffect(() => bus.on('debrief.generate', generate), [])

  const exportReport = () => {
    const blob = new Blob([buildReportMarkdown(evidence, confidence)], { type: 'text/markdown' })
    const url = URL.createObjectURL(blob)
    const a = document.createElement('a')
    a.href = url
    a.download = 'AAR-quiet-horizon.md'
    a.click()
    URL.revokeObjectURL(url)
  }

  return (
    <Pane
      eyebrow="Phase 4 · Debrief"
      title="What we found, and what to do next time"
      actions={
        <>
          <button className="btn" onClick={generate} disabled={thinking || reportFiled}>
            {thinking ? <Loader2 size={14} className="spin" /> : <Sparkles size={14} />} {reportFiled ? 'Report generated' : 'Generate report'}
          </button>
          <button className="btn btn-accent" onClick={exportReport} disabled={!reportFiled}><Download size={14} /> Export .md</button>
        </>
      }
    >
      <div className="debrief">
        <div className="answer">
          <ShieldCheck size={28} />
          <div>
            <div className="eyebrow">Answer to “{mission.question}”</div>
            <h3>Yes — staging confirmed at {Math.round(confidence * 100)}% confidence</h3>
            <p>{evidence.length} independent sources agreed. The GF-2 contact was tracked and deterred without escalation.</p>
          </div>
        </div>

        <div className="stats">
          {aarReport.stats.map((s) => (
            <div key={s.label} className="stat">
              <b>{s.value}</b>
              <span>{s.label}</span>
            </div>
          ))}
        </div>

        <div className="debrief-cols">
          <div>
            <div className="eyebrow">Timeline</div>
            <ol className="timeline">
              {aarReport.timeline.map((t) => (
                <li key={t.t} className={`sev-${t.sev}`}>
                  <span className="mono">{t.t}</span>
                  <span>{t.label}</span>
                </li>
              ))}
            </ol>
          </div>
          <div>
            <div className="eyebrow">After-action synthesis</div>
            {!reportFiled && !thinking && <div className="placeholder">Generate the report to see findings, lessons learned and the recommendation.</div>}
            {thinking && <div className="placeholder"><Loader2 size={14} className="spin" /> Synthesizing the full operation archive…</div>}
            {reportFiled && (
              <div className="aar">
                <h4>Findings</h4><p>{aarReport.findings}</p>
                <h4>Lessons learned</h4><p>{aarReport.lessons}</p>
                <h4>Recommendation</h4><p className="accent">{aarReport.recommendation}</p>
              </div>
            )}
          </div>
        </div>
      </div>
    </Pane>
  )
}
