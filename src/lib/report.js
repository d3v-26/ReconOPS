import { aarReport, mission, evidenceSources, anomalies } from '../data/mockData.js'

export function reportStats(ops) {
  const resolved = anomalies.filter((a) => ops.statusOf(a.id) !== 'Open').length
  return [
    { label: 'Confidence', value: `${Math.round(ops.confidence * 100)}%` },
    { label: 'Sources logged', value: String(ops.evidence.length) },
    { label: 'Entities inspected', value: String(ops.viewed.length) },
    { label: 'Alerts resolved', value: `${resolved}/${anomalies.length}` },
    { label: 'Escalations', value: '0' },
  ]
}

function buildReportMarkdown(ops) {
  return [
    `# AFTER-ACTION REPORT — ${mission.title}`,
    `\n> PREVIEW // MOCK — fictional scenario, generated by Ghost Command: ReconOps demo\n`,
    `## Question\n${mission.question}\n`,
    `## Answer\nStaging confirmed — ${Math.round(ops.confidence * 100)}% confidence from ${ops.evidence.length} independent sources.\n`,
    `## Evidence\n${evidenceSources.filter((s) => ops.evidence.includes(s.id)).map((s) => `- **${s.label}:** ${s.finding}`).join('\n')}\n`,
    `## Statistics\n${reportStats(ops).map((s) => `- ${s.label}: ${s.value}`).join('\n')}\n`,
    `## Timeline\n${aarReport.timeline.map((t) => `- **${t.t}** [${t.sev}] ${t.label}`).join('\n')}\n`,
    `## Findings\n${aarReport.findings}\n`,
    `## Lessons Learned\n${aarReport.lessons}\n`,
    `## Recommendation\n${aarReport.recommendation}\n`,
  ].join('\n')
}

export function exportReport(ops) {
  const blob = new Blob([buildReportMarkdown(ops)], { type: 'text/markdown' })
  const url = URL.createObjectURL(blob)
  const a = document.createElement('a')
  a.href = url
  a.download = 'AAR-quiet-horizon.md'
  a.click()
  URL.revokeObjectURL(url)
}
